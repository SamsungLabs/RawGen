"""
Dataset class for loading anchor-variant latent pairs for diffusion training.

This module provides VariantAnchorLatentDataset for loading:
- Anchor latent tensors (target denoised state)
- Variant latent tensors (conditioned input)
- Multiple variations per anchor latent

All latents are generated by generate_latents_for_variants_and_anchors.py
"""

from pathlib import Path
from typing import List, Tuple, Optional, Union

import torch
from torch.utils.data import Dataset

from .dataset import load_manifest_pairs


class VariantAnchorLatentDataset(Dataset):
    """
    Dataset for loading anchor-variant latent pairs for diffusion training.

    Latents are already stored as .pt files from generate_latents_for_variants_and_anchors.py.
    No need to load images - only latent tensors are used.

    Loads:
    - Anchor XYZ latents (targets for denoising)
    - Variant latents (for conditioning)

    Each anchor has multiple variant pairs for data augmentation.

    Args:
        manifest_path: Path to trainval.json manifest
        split: "train", "val", "test", or "all"
        datasets: Dataset subset to include (e.g., "a5k", "raise", or "all")
        num_variations: Number of variant pairs per anchor
        latent_dir_name: Subdirectory name under each dataset folder containing latents
    """

    def __init__(
        self,
        manifest_path: Path,
        root_key: str = "root",
        split: str = "train",
        datasets: Union[str, List[str]] = "all",
        num_variations: int = 5,
        latent_dir_name: str = "latents",
    ):
        self.manifest_path = manifest_path
        self.split = split
        self.num_variations = num_variations
        self.latent_dir_name = latent_dir_name
        self.meta_root = None  # Will be set after loading manifest

        if split not in {"train", "val", "test", "all"}:
            raise ValueError("split must be 'train', 'val', 'test', or 'all'")

        # Map datasets ("all", "+"-joined string, or list) to list expected by manifest loader
        if datasets is None or (isinstance(datasets, str) and datasets.lower() == "all"):
            dataset_subsets: Optional[List[str]] = None
        else:
            if isinstance(datasets, str):
                dataset_subsets = [d.strip() for d in datasets.split("+") if d.strip()]
            else:
                dataset_subsets = list(datasets)

        # Load manifest to get valid pairs and meta info
        pairs, meta = load_manifest_pairs(manifest_path, dataset_subsets, split=split, root_key=root_key)
        self.meta_root = Path(meta.get("root", "."))
        meta_root = self.meta_root
        xyz_suffix = meta.get("xyz_suffix", "_xyz.png")

        # Build samples list from manifest
        self.samples = []
        skipped = 0

        for _srgb_path, xyz_path in pairs:
            xyz_path = Path(xyz_path)
            # Infer dataset type from path: <root>/<dataset_type>/XYZ/<file>
            try:
                dataset_type = xyz_path.parents[1].name
            except Exception:
                dataset_type = xyz_path.parent.name  # fallback

            # Determine latent directory for this dataset type
            latent_dir = meta_root / dataset_type / self.latent_dir_name

            # Derive basename from xyz filename by removing xyz_suffix
            filename = xyz_path.name
            if filename.endswith(xyz_suffix):
                basename = filename[: -len(xyz_suffix)]
            else:
                basename = xyz_path.stem.replace("_xyz", "")

            anchor_target_path = latent_dir / f"{basename}_anchor_xyz.pt"
            if not anchor_target_path.exists():
                skipped += 1
                continue

            # Check that all variant latents exist
            var_latent_paths = [
                latent_dir / f"{basename}_var_{i:02d}.pt"
                for i in range(num_variations)
            ]
            if not all(p.exists() for p in var_latent_paths):
                skipped += 1
                continue

            self.samples.append({
                "basename": basename,
                "anchor_target_path": anchor_target_path,
                "var_latent_paths": var_latent_paths,
                "dataset_type": dataset_type,
            })

        if skipped > 0:
            print(f"[WARN] {skipped} samples skipped due to missing files in split '{split}'")

        if not self.samples:
            raise ValueError(f"No valid samples found in split '{split}'")

        print(f"Loaded {len(self.samples)} anchor-variant pairs for {split} split")

    def __len__(self) -> int:
        # Multiple variations per anchor
        return len(self.samples) * self.num_variations

    def __getitem__(self, idx: int) -> Tuple:
        """
        Load a single training sample.

        Returns:
            - anchor_latent: Target XYZ latent (shape: [C, H, W])
            - variant_latent: Conditioning latent from variant (shape: [C, H, W])
            - basename: Sample basename
            - variation_idx: Which variation (0 to num_variations-1)
        """
        anchor_idx = idx // self.num_variations
        variation_idx = idx % self.num_variations

        sample = self.samples[anchor_idx]
        basename = sample["basename"]

        # Load anchor target latent
        anchor_data = torch.load(sample["anchor_target_path"], map_location="cpu")
        anchor_latent = anchor_data["latent"].float()

        # Load variant latent
        var_latent_data = torch.load(sample["var_latent_paths"][variation_idx], map_location="cpu")
        variant_latent = var_latent_data["latent"].float()

        return anchor_latent, variant_latent, basename, variation_idx
